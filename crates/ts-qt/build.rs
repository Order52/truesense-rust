//! Builds the Qt app: the QML module, its resources, the translations and the C++ shim.
//!
//! Nothing here is edited when a page is added. The build **discovers**
//!
//! * every `qml/**/*.qml` (compiled ahead of time by qmlcachegen; a file that contains
//!   `pragma Singleton` is registered as a singleton);
//! * every other file under `qml/` (icons, data) as a resource beside the QML;
//! * every `src/models/*.rs` that contains `#[cxx_qt::bridge` as a cxx-qt bridge, and every
//!   `src/models/*.rs` as a module (the generated `models_gen.rs` lists them);
//! * every `i18n/*.ts`, compiled by `lrelease` into `:/i18n/<name>.qm`, plus the
//!   pseudo-locale made from `en.ts` (`pseudo.qm`), for tests.
//!
//! Qt's tools come from `QMAKE` (default `qmake6`): `qmake -query QT_INSTALL_LIBEXECS` and `.../bin`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::{env, fs};

use cxx_qt_build::{CxxQtBuilder, QmlFile, QmlModule};
use qt_build_utils::{QResource, QResourceFile, QResources};

#[path = "../ts-ui-model/src/pseudo.rs"]
#[allow(dead_code, missing_docs)]
mod pseudo;

const URI: &str = "org.truesense.app";

fn fail(message: &str) -> ! {
    println!("cargo::error={message}");
    std::process::exit(1)
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    let mut entries: Vec<_> = entries.flatten().map(|e| e.path()).collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            walk(&path, out);
        } else {
            out.push(path);
        }
    }
}

fn relative(path: &Path, base: &Path) -> String {
    path.strip_prefix(base).unwrap_or(path).to_string_lossy().replace('\\', "/")
}

/// The directory holding `lrelease`: asks qmake, then falls back to well-known places and PATH.
fn lrelease() -> PathBuf {
    let qmake = env::var("QMAKE").unwrap_or_else(|_| "qmake6".to_owned());
    for key in ["QT_INSTALL_BINS", "QT_INSTALL_LIBEXECS"] {
        if let Ok(out) = Command::new(&qmake).args(["-query", key]).output() {
            let dir = PathBuf::from(String::from_utf8_lossy(&out.stdout).trim());
            for name in ["lrelease", "lrelease6", "lrelease-qt6"] {
                if dir.join(name).is_file() {
                    return dir.join(name);
                }
            }
        }
    }
    for dir in ["/usr/lib/qt6/bin", "/usr/lib64/qt6/bin", "/usr/bin"] {
        for name in ["lrelease", "lrelease6", "lrelease-qt6"] {
            if Path::new(dir).join(name).is_file() {
                return Path::new(dir).join(name);
            }
        }
    }
    PathBuf::from("lrelease")
}

fn compile_ts(lrelease: &Path, ts: &Path, qm: &Path) {
    let status = Command::new(lrelease).arg("-silent").arg(ts).arg("-qm").arg(qm).status();
    match status {
        Ok(s) if s.success() && qm.is_file() => {}
        Ok(s) => fail(&format!("lrelease failed on {} ({s})", ts.display())),
        Err(e) => fail(&format!("cannot run lrelease ({}): {e}", lrelease.display())),
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let out = PathBuf::from(env::var("OUT_DIR").unwrap_or_default());
    println!("cargo:rerun-if-changed=qml");
    println!("cargo:rerun-if-changed=i18n");
    println!("cargo:rerun-if-changed=src/models");
    println!("cargo:rerun-if-changed=cpp");
    println!("cargo:rerun-if-changed=assets");

    // ---- QML files and the resources beside them --------------------------------------------
    let mut all = Vec::new();
    walk(&manifest.join("qml"), &mut all);
    let mut qml_files = Vec::new();
    let mut resources = Vec::new();
    for path in all {
        let rel = relative(&path, &manifest);
        if path.extension().is_some_and(|e| e == "qml") {
            let singleton =
                fs::read_to_string(&path).is_ok_and(|t| t.lines().any(|l| l.trim() == "pragma Singleton"));
            qml_files.push(QmlFile::from(rel).singleton(singleton));
        } else {
            resources.push(rel);
        }
    }
    let module = QmlModule::new(URI)
        .depend("QtQuick")
        .depend("QtQuick.Controls.Basic")
        .depend("QtQuick.Layouts")
        .qml_files(qml_files);

    // ---- bridges and view-model modules of page agents --------------------------------------
    let mut bridges = vec!["src/bus_object.rs".to_owned()];
    let mut models = String::from("// Generated by build.rs: one module per file of src/models.\n");
    let mut model_files = Vec::new();
    walk(&manifest.join("src/models"), &mut model_files);
    for path in model_files {
        if path.extension().is_none_or(|e| e != "rs") || path.file_stem().is_some_and(|s| s == "mod") {
            continue;
        }
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("").to_owned();
        let _ = writeln!(models, "#[path = {:?}]\npub mod {stem};", path.display().to_string());
        if fs::read_to_string(&path).is_ok_and(|t| t.contains("#[cxx_qt::bridge")) {
            bridges.push(relative(&path, &manifest));
        }
    }
    if let Err(e) = fs::write(out.join("models_gen.rs"), models) {
        fail(&format!("cannot write models_gen.rs: {e}"));
    }

    // ---- translations -----------------------------------------------------------------------
    let lrelease = lrelease();
    let qm_dir = out.join("qm");
    if let Err(e) = fs::create_dir_all(&qm_dir) {
        fail(&format!("cannot create {}: {e}", qm_dir.display()));
    }
    let mut qms = Vec::new();
    let mut ts_files = Vec::new();
    walk(&manifest.join("i18n"), &mut ts_files);
    for ts in ts_files.iter().filter(|p| p.extension().is_some_and(|e| e == "ts")) {
        let name = ts.file_stem().and_then(|s| s.to_str()).unwrap_or("x");
        let qm = qm_dir.join(format!("{name}.qm"));
        compile_ts(&lrelease, ts, &qm);
        qms.push((name.to_owned(), qm));
        if name == "en" {
            let text = fs::read_to_string(ts).unwrap_or_default();
            let pseudo_ts = qm_dir.join("pseudo.ts");
            if let Err(e) = fs::write(&pseudo_ts, pseudo::pseudo_ts(&text)) {
                fail(&format!("cannot write pseudo.ts: {e}"));
            }
            let qm = qm_dir.join("pseudo.qm");
            compile_ts(&lrelease, &pseudo_ts, &qm);
            qms.push(("pseudo".to_owned(), qm));
        }
    }

    let i18n = QResource::new()
        .prefix("/i18n")
        .files(qms.iter().map(|(name, qm)| QResourceFile::new(qm).alias(format!("{name}.qm"))));
    let assets = QResource::new().prefix("/assets").files(
        fs::read_dir(manifest.join("assets"))
            .into_iter()
            .flatten()
            .flatten()
            .map(|e| QResourceFile::new(e.path()).alias(e.file_name().to_string_lossy().into_owned())),
    );

    CxxQtBuilder::new_qml_module(module)
        .qrc_resources(resources)
        .qrc_resources(QResources::new().resource(i18n))
        .qrc_resources(QResources::new().resource(assets))
        .files(bridges)
        .include_dir("cpp")
        .cpp_files(["cpp/shim.cpp", "cpp/shim.h"])
        .qt_module("Quick")
        .build();
}
